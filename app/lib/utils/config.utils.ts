import {Config} from "../config"

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
export const getAppLangs = () => {
  const appLangs = Config.globals.languages.available.map(l => l.key)
  return appLangs
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
export const getAppCurrencies = () => {
  const appCurrencies = Config.globals.currencies.available.map(l => l.key)
  return appCurrencies
}

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
export const getAppDimensionsUnits = () => {
  const appDimensionsUnits = Config.globals.dimensionsUnits.available.map(l => l.key)
  return appDimensionsUnits
}
