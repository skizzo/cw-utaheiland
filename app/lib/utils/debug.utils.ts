///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
export const bgd = (DEBUG: boolean, backgroundColor: string, backgroundColorNoDebug?: string) => (DEBUG ? {backgroundColor} : {...(backgroundColorNoDebug ? {backgroundColor: backgroundColorNoDebug} : {})})

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
export const brd = (DEBUG: boolean, color: string, width = 1) => (DEBUG ? {border: `${width}px solid ${color}` as const} : {})
